"""Translate the pinned Anime4K CNN x2 S's four convolutions into Metal.

GLSL and Metal both use column-major matrices. Explicit column vectors preserve
the original scalar weight ordering. The final depth-to-space pass follows the
source hook at output texel centers, with clamp-to-edge bilinear base sampling.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'native/gdi-upscalers/vendor/anime4k/Anime4K_Upscale_CNN_x2_S.glsl'


def generate(source):
    blocks = source.split('//!DESC ')[1:]
    if len(blocks) != 5 or 'Depth-to-Space' not in blocks[-1]:
        raise ValueError('Expected the pinned four-convolution Anime4K network')
    license_text = source.split('//!DESC ')[0]
    output = [license_text, '// Generated by scripts/generate-anime4k-metal.py.\n',
              '#include <metal_stdlib>\nusing namespace metal;\n', '''
inline float4 read_edge(texture2d<float, access::read> image, int2 coordinate)
{
    int2 limit = int2(image.get_width(), image.get_height()) - 1;
    return image.read(uint2(clamp(coordinate, int2(0), limit)));
}
''']

    def matrix(match):
        weights = [weight.strip() for weight in match[1].split(',')]
        if len(weights) != 16:
            raise ValueError('Expected a 4x4 weight matrix')
        columns = ['float4(' + ', '.join(weights[i:i+4]) + ')' for i in range(0, 16, 4)]
        return 'float4x4(' + ', '.join(columns) + ')'

    for index, block in enumerate(blocks[:4]):
        if block.count('vec4 hook()') != 1:
            raise ValueError('Unexpected shader hook')
        body = block.split('vec4 hook() {', 1)[1].split('\n}', 1)[0]
        if body.count('go_0(') != 9 or body.count('go_1(') != (0 if index == 0 else 9):
            raise ValueError('Unexpected convolution tap count')
        body = re.sub(r'mat4\(([^)]+)\)', matrix, body).replace('vec4', 'float4')
        body = body.replace('return result;', 'destination.write(result, gid);')
        positive = 'read_edge(source, int2(gid) + int2(x, y))'
        if index:
            positive = 'max(' + positive + ', 0.0)'
        output.append(f'#define go_0(x, y) ({positive})\n')
        if index:
            output.append('#define go_1(x, y) (max(-read_edge(source, int2(gid) + int2(x, y)), 0.0))\n')
        output.append(f'''kernel void convolution{index}(
    texture2d<float, access::read> source [[texture(0)]],
    texture2d<float, access::write> destination [[texture(1)]],
    uint2 gid [[thread_position_in_grid]])
{{
    if (gid.x >= destination.get_width() || gid.y >= destination.get_height()) return;
{body}
}}
#undef go_0
''')
        if index:
            output.append('#undef go_1\n')
    output.append('''
kernel void depth_to_space(
    texture2d<float, access::read> features [[texture(0)]],
    texture2d<float, access::sample> original [[texture(1)]],
    texture2d<float, access::write> destination [[texture(2)]],
    uint2 gid [[thread_position_in_grid]])
{
    if (gid.x >= destination.get_width() || gid.y >= destination.get_height()) return;
    constexpr sampler bilinear(coord::normalized, address::clamp_to_edge, filter::linear);
    float2 uv = (float2(gid) + 0.5) / float2(destination.get_width(), destination.get_height());
    float residual = features.read(gid / 2)[(gid.y % 2) * 2 + gid.x % 2];
    float3 rgb = original.sample(bilinear, uv).rgb + residual;
    destination.write(float4(clamp(rgb, 0.0, 1.0), 1.0), gid);
}
''')
    return ''.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(SOURCE.read_text()))
